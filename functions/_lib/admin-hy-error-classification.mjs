function errorCode(error) {
  return error && typeof error === 'object' && typeof error.code === 'string' ? error.code : null;
}

// Atomic HY writes distinguish repository-state failures from client input and
// GitHub transport failures. Do not expose internal messages in 5xx responses.
export function classifyAdminHyWriteError(error) {
  const code = errorCode(error);
  if (code === 'BRANCH_REF_UPDATE_FAILURE') {
    return { kind: 'commit_outcome_unknown', status: 502 };
  }
  if (CONFLICT_CODES.has(code)) return { kind: 'conflict', status: 409 };
  if (UPSTREAM_CODES.has(code)) return { kind: 'upstream', status: 502, code: 'UPSTREAM_FAILURE' };
  if (CONFIGURATION_CODES.has(code)) {
    return { kind: 'configuration', status: 503, code: 'SERVICE_UNAVAILABLE' };
  }
  if (VALIDATION_CODES.has(code)) {
    return { kind: 'validation', status: 400 };
  }
  if (INTEGRITY_CODES.has(code)) {
    return { kind: 'integrity', status: 503, code: 'REPOSITORY_INTEGRITY' };
  }
  return null;
}
